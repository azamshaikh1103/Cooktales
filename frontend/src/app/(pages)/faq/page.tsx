const FAQ_SCHEMA = {
	"@context": "https://schema.org",
	"@type": "FAQPage",
	mainEntity: FAQ_DATA.flatMap((section) =>
		section.items.map((item) => ({
			"@type": "Question",
			name: item.question,
			acceptedAnswer: { "@type": "Answer", text: item.answer },
		})),
	),
};

const FAQ_SCHEMA_JSON = JSON.stringify(FAQ_SCHEMA).replace(/</g, "\\u003c");

export default function FAQPage() {
	const [searchQuery, setSearchQuery] = useState("");
	const [openItems, setOpenItems] = useState<string[]>([]);
	const normalizedQuery = searchQuery.trim().toLowerCase();

	const filteredData = useMemo(
		() =>
			FAQ_DATA.map((section) => ({
				...section,
				items: section.items.filter(
					(item) =>
						item.question.toLowerCase().includes(normalizedQuery) ||
						item.answer.toLowerCase().includes(normalizedQuery),
				),
			})).filter((section) => section.items.length > 0),
		[normalizedQuery],
	);

	const toggleItem = (id: string) => {
		setOpenItems((current) =>
			current.includes(id)
				? current.filter((item) => item !== id)
				: [...current, id],
		);
	};

	return (
		<div className="flex min-h-screen flex-col bg-[#fafafa] text-gray-900 transition-colors duration-500 dark:bg-[#0d1f1c] dark:text-white">
			<script type="application/ld+json">{FAQ_SCHEMA_JSON}</script>
			<Navbar />
			<main className="grow pt-24 pb-20 lg:pt-32">
				<div className="mx-auto max-w-5xl px-6 lg:px-24">
					<header className="mx-auto mb-14 max-w-3xl text-center lg:mb-16">
						<div className="mb-6 inline-flex items-center gap-2 rounded-full border border-gray-200 bg-white px-4 py-1.5 text-xs font-bold tracking-widest text-[#006C5E] uppercase dark:border-white/10 dark:bg-white/5 dark:text-[#4ADE80]">
							<FaQuestionCircle /> Help centre
						</div>
						<h1 className="mb-5 text-4xl leading-tight font-black lg:text-6xl">
							Answers for readers and creators.
						</h1>
						<p className="text-lg leading-relaxed text-gray-500 dark:text-gray-400">
							Clear answers about CookTale, publishing recipes, creator
							earnings, and account support.
						</p>
						<label className="group relative mt-9 block text-left">
							<span className="sr-only">Search frequently asked questions</span>
							<FaSearch className="pointer-events-none absolute top-1/2 left-5 -translate-y-1/2 text-gray-400 group-focus-within:text-[#006C5E] dark:group-focus-within:text-[#4ADE80]" />
							<input
								type="search"
								placeholder="Search questions"
								value={searchQuery}
								onChange={(event) => setSearchQuery(event.target.value)}
								className="w-full rounded-2xl border border-gray-200 bg-white py-4 pr-5 pl-12 text-sm outline-none transition-colors placeholder:text-gray-400 focus:border-[#006C5E] focus:ring-2 focus:ring-[#006C5E]/15 dark:border-white/10 dark:bg-white/5 dark:text-white dark:focus:border-[#4ADE80] dark:focus:ring-[#4ADE80]/15"
							/>
						</label>
					</header>

					<div className="space-y-12">
						{filteredData.length ? (
							filteredData.map((section) => {
								const Icon = section.icon;
								return (
									<section key={section.category}>
										<div className="mb-5 flex items-center gap-3">
											<span className="text-lg text-[#006C5E] dark:text-[#4ADE80]">
												<Icon />
											</span>
											<h2 className="text-2xl font-black">
												{section.category}
											</h2>
										</div>
										<div className="overflow-hidden rounded-2xl border border-gray-200 bg-white dark:border-white/10 dark:bg-white/5">
											{section.items.map((item, index) => {
												const id = `${section.category}-${index}`;
												const isOpen = openItems.includes(id);
												return (
													<div
														key={item.question}
														className="border-b border-gray-100 last:border-0 dark:border-white/10"
													>
														<button
															type="button"
															onClick={() => toggleItem(id)}
															aria-expanded={isOpen}
															aria-controls={`${id}-answer`}
															className="flex w-full cursor-pointer items-center justify-between gap-6 px-6 py-5 text-left font-bold transition-colors hover:bg-gray-50 dark:hover:bg-white/5"
														>
															<span>{item.question}</span>
															<FaChevronDown
																className={`shrink-0 text-sm text-gray-400 transition-transform ${isOpen ? "rotate-180 text-[#006C5E] dark:text-[#4ADE80]" : ""}`}
															/>
														</button>
														{isOpen && (
															<p
																id={`${id}-answer`}
																className="border-t border-gray-100 px-6 py-5 leading-relaxed text-gray-600 dark:border-white/10 dark:text-gray-300"
															>
																{item.answer}
															</p>
														)}
													</div>
												);
											})}
										</div>
									</section>
								);
							})
						) : (
							<div className="rounded-2xl border border-gray-200 bg-white px-6 py-14 text-center text-gray-500 dark:border-white/10 dark:bg-white/5 dark:text-gray-400">
								No answers match “{searchQuery}”. Try a different word or
								contact us.
							</div>
						)}
					</div>

					<section className="mt-16 rounded-3xl bg-[#006C5E] p-8 text-center text-white lg:p-12">
						<FaEnvelope className="mx-auto mb-4 text-2xl" />
						<h2 className="mb-3 text-3xl font-black">Still need help?</h2>
						<p className="mx-auto mb-7 max-w-lg text-white/80">
							Send us the page link and a short description of what you need.
						</p>
						<PrimaryActionLink
							href="/contact"
							className="bg-white text-[#006C5E] hover:bg-gray-100 dark:bg-white dark:text-[#006C5E] dark:hover:bg-gray-100"
						>
							Contact CookTale
						</PrimaryActionLink>
					</section>
				</div>
			</main>
			<Footer />
		</div>
	);
}
